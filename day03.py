# Day  3 - Numbers and Math

# Example 1: Freight Cost
rate_per_kg = 50
weight_kg = 120
total_cost = rate_per_kg * weight_kg
print("Total freight cost:", total_cost)

# Example 2: Days Calculation
total_hours = 50
hours_per_day = 8
full_days = total_hours // hours_per_day
remaining = total_hours % hours_per_day
print("Full days:", full_days)
print("Remaining hours:", remaining)

# Example 3: Average Speed
distance_km = 450
time_hours = 6
speed = distance_km / time_hours
print("Average speed:", speed, "km/h")

# Example 4: BODMAS
print(10 + 5 * 2)
print((10 + 5) * 2)

# Example 5: Type Conversion
age = "24"
age_number = int(age)
print("Next year age:", age_number + 1)